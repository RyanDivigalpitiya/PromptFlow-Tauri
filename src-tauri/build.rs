use std::fmt::Write as _;
use std::path::Path;

/// Bake every `.md` in `prompt-templates/` into the binary as the DEFAULT templates: what
/// `templates::scan` writes into a fresh templates folder. At run time the folder is the
/// only source (see `src/templates.rs`); this table is just what fills it the first time.
/// A file here that isn't valid UTF-8 fails the `include_str!`, which is the right place
/// to hear about it.
fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../prompt-templates");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut found: Vec<String> = Vec::new();
    match std::fs::read_dir(&dir) {
        Ok(entries) => {
            for entry in entries.flatten() {
                let name = entry.file_name().to_string_lossy().to_string();
                if name.starts_with('.') {
                    continue;
                }
                if !name.to_lowercase().ends_with(".md") {
                    println!("cargo:warning=prompt-templates/{name} is not a .md file, so it is not a default template");
                    continue;
                }
                println!("cargo:rerun-if-changed={}", entry.path().display());
                found.push(name);
            }
        }
        Err(_) => println!(
            "cargo:warning=prompt-templates/ not found at {} — a new templates folder will start empty",
            dir.display()
        ),
    }
    found.sort();

    let mut src = String::from(
        "// @generated by build.rs from prompt-templates/ — do not edit.\n\
         pub static DEFAULTS: &[(&str, &str)] = &[\n",
    );
    for name in &found {
        let _ = writeln!(
            src,
            "    ({:?}, include_str!({:?})),",
            name,
            dir.join(name).to_string_lossy()
        );
    }
    src.push_str("];\n");

    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("templates_generated.rs");
    std::fs::write(&out, src).expect("write templates_generated.rs");

    tauri_build::build()
}
